const db = require('./src/db');

async function migrate() {
  const exists = async (table) => (await db.query('SELECT RDB$RELATION_NAME FROM RDB$RELATIONS WHERE RDB$RELATION_NAME=?', [table])).length;
  if (!await exists('TPHATSINHSUACHUA')) {
    await db.execute(`CREATE TABLE TPHATSINHSUACHUA (
      ID VARCHAR(36) NOT NULL PRIMARY KEY,
      TLENHSUACHUAID VARCHAR(36) NOT NULL REFERENCES TLENHSUACHUA(ID),
      LYDO VARCHAR(1000) CHARACTER SET UTF8 NOT NULL,
      TRANGTHAI VARCHAR(24) NOT NULL,
      NGUOIXACNHAN VARCHAR(200) CHARACTER SET UTF8,
      BANGCHUNG VARCHAR(2000) CHARACTER SET UTF8,
      NGAYXACNHAN TIMESTAMP,
      USERCREATEDID VARCHAR(36) NOT NULL,
      TIMECREATED TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
      USERMODIFIEDID VARCHAR(36), TIMEMODIFIED TIMESTAMP,
      CONSTRAINT CK_PS_STATE CHECK (TRANGTHAI IN ('draft','pending','approved','partially_approved','rejected','cancelled'))
    )`);
  }
  if (!await exists('TPHATSINHSUACHUACT')) {
    await db.execute(`CREATE TABLE TPHATSINHSUACHUACT (
      ID VARCHAR(36) NOT NULL PRIMARY KEY,
      TPHATSINHSUACHUAID VARCHAR(36) NOT NULL REFERENCES TPHATSINHSUACHUA(ID),
      LOAI SMALLINT NOT NULL, DMATHANGID VARCHAR(36) REFERENCES DMATHANG(ID),
      DDICHVUID VARCHAR(36) REFERENCES DDICHVU(ID), DDONVITINHID VARCHAR(36),
      TEN VARCHAR(255) CHARACTER SET UTF8 NOT NULL,
      SOLUONG NUMERIC(18,3) NOT NULL, DONGIA NUMERIC(18,2) NOT NULL,
      THANHTIEN NUMERIC(18,2) NOT NULL, TRANGTHAI VARCHAR(24) DEFAULT 'pending' NOT NULL,
      CONSTRAINT CK_PS_CT_AMOUNT CHECK (SOLUONG>0 AND DONGIA>=0),
      CONSTRAINT CK_PS_CT_KIND CHECK ((LOAI=0 AND DMATHANGID IS NOT NULL AND DDICHVUID IS NULL) OR (LOAI=1 AND DDICHVUID IS NOT NULL AND DMATHANGID IS NULL)),
      CONSTRAINT CK_PS_CT_STATE CHECK (TRANGTHAI IN ('pending','approved','rejected','cancelled'))
    )`);
  }
  const fields = await db.query("SELECT RDB$FIELD_NAME FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME='TLENHSUACHUACHITIET' AND RDB$FIELD_NAME='PHATSINHCTID'");
  if (!fields.length) {
    await db.execute('ALTER TABLE TLENHSUACHUACHITIET ADD PHATSINHCTID VARCHAR(36) REFERENCES TPHATSINHSUACHUACT(ID)');
  }
  for (const [name, sql] of [
    ['IX_PS_REPAIR', 'CREATE INDEX IX_PS_REPAIR ON TPHATSINHSUACHUA(TLENHSUACHUAID)'],
    ['IX_PS_CT_HEAD', 'CREATE INDEX IX_PS_CT_HEAD ON TPHATSINHSUACHUACT(TPHATSINHSUACHUAID)'],
    ['UX_REPAIR_PS_CT', 'CREATE UNIQUE INDEX UX_REPAIR_PS_CT ON TLENHSUACHUACHITIET(PHATSINHCTID)'],
  ]) {
    if (!(await db.query('SELECT RDB$INDEX_NAME FROM RDB$INDICES WHERE RDB$INDEX_NAME=?', [name])).length) await db.execute(sql);
  }
  console.log('Repair supplement schema ready.');
}
if (require.main === module) migrate().then(() => process.exit(0)).catch(e => { console.error(e); process.exit(1); });
module.exports = migrate;
