import {useEffect,useRef,useState} from 'react';
import api from '../api.js';

export default function useEditableCodePreview(type, field, form, setForm, enabled) {
  const touched=useRef(false);
  const [loading,setLoading]=useState(false);
  useEffect(() => {
    if(!enabled) return;
    touched.current=Boolean(form?.[field]);
    if(touched.current) return;
    const controller=new AbortController();
    setLoading(true);
    api.get(`/document-numbers/${type}/next`,{signal:controller.signal}).then(response => {
      if(controller.signal.aborted || touched.current) return;
      const code=String(response.data.code).toUpperCase();
      setForm(current => current && !current[field] ? {...current,[field]:code,AUTO_CODE:code} : current);
    }).catch(() => {}) // An empty code is generated by the server when saving.
      .finally(() => {if(!controller.signal.aborted)setLoading(false);});
    return () => controller.abort();
  },[type,field,enabled]);
  const changeCode=value => {
    touched.current=true;
    setForm(current => ({...current,[field]:value,AUTO_CODE:''}));
  };
  return {loading,changeCode};
}
